export function filterEmojis(query: string, limit = 30): EmojiMatch[] {
  const normalized = query.toLowerCase();
  if (!normalized) {
    return EMOJI_DATA.slice(0, 12).map(([alias, emoji]) => ({ alias, emoji }));
  }

  const exact: EmojiMatch[] = [];
  const starts: EmojiMatch[] = [];
  const contains: EmojiMatch[] = [];
  for (const [alias, emoji] of EMOJI_DATA) {
    if (alias === normalized) {
      exact.push({ alias, emoji });
    } else if (alias.startsWith(normalized)) {
      starts.push({ alias, emoji });
    } else if (alias.includes(normalized)) {
      contains.push({ alias, emoji });
    }
    if (exact.length + starts.length >= limit) {
      break;
    }
  }

  return [...exact, ...starts, ...contains].slice(0, limit);
}
